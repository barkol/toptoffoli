def save_serializable_results(results, output_file):
    """Save results to a JSON file, handling non-serializable objects"""
    serializable_results = {}
    
    for method, results_by_fidelity in results.items():
        serializable_results[method] = {}
        
        for fidelity, result in results_by_fidelity.items():
            # Create a serializable copy
            serializable_result = {}
            
            for key, value in result.items():
                # Skip circuit objects and other non-serializable things
                if key != "circuit":
                    serializable_result[key] = value
            
            serializable_results[method][fidelity] = serializable_result
    
    with open(output_file, 'w') as f:
        json.dump(serializable_results, f, indent=2)

def main():
    """Main function"""
    # Parse command line arguments
    args = parse_args()
    
    # Create output directory
    os.makedirs(args.output, exist_ok=True)
    
    # Load the utility functions
    define_loaded_toffoli_network, _ = load_io_utils()
    
    # Load the input Toffoli network
    print(f"Loading Toffoli network from {args.input}")
    result = define_loaded_toffoli_network(args.input, debug=args.debug)
    
    if result is None:
        print(f"Error: Failed to load Toffoli network from {args.input}")
        print("Creating a dummy Toffoli network for testing")
        
        # Create a dummy network
        toffoli_gates = [
            ([0, 1], 2),  # Controls: 0,1; Target: 2
            ([0, 1], 3),  # Controls: 0,1; Target: 3
            ([0, 2], 4),  # Controls: 0,2; Target: 4
            ([1, 2], 5),  # Controls: 1,2; Target: 5
            ([2, 3], 6),  # Controls: 2,3; Target: 6
            ([4, 5], 7),  # Controls: 4,5; Target: 7
        ]
        output_qubits = [3, 6, 7]  # Sum bits and carry
        input_qubits = [0, 1, 2]   # Input bits
    else:
        toffoli_gates, output_qubits, input_qubits = result
    
    # Determine number of qubits if not specified
    num_qubits = max([max(controls + [target]) for controls, target in toffoli_gates]) + 1
    num_qubits = max(8, num_qubits)  # Ensure at least 8 qubits
    
    print(f"Loaded Toffoli network with {len(toffoli_gates)} gates on {num_qubits} qubits")
    print(f"Input qubits: {input_qubits}")
    print(f"Output qubits: {output_qubits}")
    
    # Parse target fidelities
    target_fidelities = [float(f.strip()) for f in args.target_fidelities.split(',')]
    
    # Run the optimization sweep
    all_results = run_optimization_sweep(
        toffoli_gates,
        output_qubits,
        input_qubits,
        num_qubits,
        args.topology,
        args.num_trials,
        target_fidelities,
        args.debug,
        args.output
    )
    
    # Save results
    results_file = os.path.join(args.output, "results.json")
    save_serializable_results(all_results, results_file)
    print(f"Results saved to {results_file}")
    
    # Create results table
    table_file = os.path.join(args.output, "results_table.txt")
    create_results_table(all_results, table_file)
    print(f"Results table saved to {table_file}")
    
    # Generate visualizations if requested
    if args.visualize:
        chart_file = os.path.join(args.output, "optimization_comparison.png")
        plot_comparison_chart(all_results, chart_file)
        print(f"Comparison chart saved to {chart_file}")
    
    print("\nOptimization sweep completed successfully!")
    return 0

if __name__ == "__main__":
    sys.exit(main())
