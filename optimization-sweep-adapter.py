class ToffoliDepthOptimizerAdapter:
    """
    Adapter class that wraps ConsolidatedToffoliDepthOptimizer to match the expected interface.
    """
    
    def __init__(self, target_fidelity=0.95, max_passes=2, debug_mode=False, output_dir=None):
        """Initialize the adapter with the given parameters."""
        self.target_fidelity = target_fidelity
        self.max_passes = max_passes
        self.debug_mode = debug_mode
        self.output_dir = output_dir or "optimization_results"
        
        # Import ConsolidatedToffoliDepthOptimizer dynamically
        try:
            # Check if optimizer.py exists and load it
            optimizer_path = os.path.join(os.path.dirname(__file__), "toffoli_optimizer", "core", "optimizer.py")
            if not os.path.exists(optimizer_path):
                optimizer_path = os.path.join(os.path.dirname(__file__), "..", "toffoli_optimizer", "core", "optimizer.py")
            
            spec = importlib.util.spec_from_file_location("optimizer_module", optimizer_path)
            optimizer_module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(optimizer_module)
            
            # Get the optimizer class - try different possible names
            if hasattr(optimizer_module, "ConsolidatedToffoliDepthOptimizer"):
                self.optimizer_class = optimizer_module.ConsolidatedToffoliDepthOptimizer
                print("Using ConsolidatedToffoliDepthOptimizer")
            elif hasattr(optimizer_module, "ToffoliDepthOptimizer"):
                self.optimizer_class = optimizer_module.ToffoliDepthOptimizer
                print("Using ToffoliDepthOptimizer")
            elif hasattr(optimizer_module, "EnhancedToffoliDepthOptimizer"):
                self.optimizer_class = optimizer_module.EnhancedToffoliDepthOptimizer
                print("Using EnhancedToffoliDepthOptimizer")
            else:
                # Fallback - create a dummy optimizer
                print("No suitable optimizer found in optimizer.py")
                self.optimizer_class = type('DummyOptimizer', (), {'__init__': lambda self, **kwargs: None})
        
        except Exception as e:
            print(f"Error importing optimizer: {e}")
            traceback.print_exc()
            # Create a dummy optimizer class as fallback
            self.optimizer_class = type('DummyOptimizer', (), {'__init__': lambda self, **kwargs: None})
        
        # Create the optimizer instance
        self.optimizer = self.optimizer_class(
            target_fidelity=target_fidelity,
            max_passes=max_passes,
            debug_mode=debug_mode,
            output_dir=self.output_dir
        )
        
        # Import compiler dynamically
        try:
            # Check if compiler.py exists and load it
            compiler_path = os.path.join(os.path.dirname(__file__), "toffoli_optimizer", "core", "compiler.py")
            if not os.path.exists(compiler_path):
                compiler_path = os.path.join(os.path.dirname(__file__), "..", "toffoli_optimizer", "core", "compiler.py")
            
            spec = importlib.util.spec_from_file_location("compiler_module", compiler_path)
            compiler_module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(compiler_module)
            
            # Get the compiler class
            if hasattr(compiler_module, "ToffoliCompiler"):
                self.compiler_class = compiler_module.ToffoliCompiler
                print("Using ToffoliCompiler")
                self.compiler = self.compiler_class(debug_mode=debug_mode)
                self.optimizer.compiler = self.compiler
            else:
                print("ToffoliCompiler not found in compiler.py")
                self.compiler_class = None
                self.compiler = None
        
        except Exception as e:
            print(f"Error importing compiler: {e}")
            traceback.print_exc()
            self.compiler_class = None
            self.compiler = None
    
    def optimize_toffoli_network(self, toffoli_gates, output_qubits, input_qubits, num_qubits, 
                              topology=None, coupling_map=None, basis_gates=None, target_fidelity=None,
                              original_circuit=None, logical_circuit=None):
        """
        Adapt and call the underlying optimizer with the given parameters.
        """
        try:
            # Call the actual optimizer
            results = self.optimizer.optimize_toffoli_network(
                toffoli_gates=toffoli_gates,
                output_qubits=output_qubits,
                input_qubits=input_qubits,
                num_qubits=num_qubits,
                topology=topology,
                coupling_map=coupling_map,
                basis_gates=basis_gates,
                target_fidelity=target_fidelity or self.target_fidelity,
                original_circuit=original_circuit,
                logical_circuit=logical_circuit
            )
            
            # Ensure results has all expected fields
            if "naive_physical" not in results and "original" in results:
                results["naive_physical"] = results["original"]
            
            if "naive_physical" not in results:
                results["naive_physical"] = {
                    "depth": 0,
                    "gate_count": 0,
                    "cx_count": 0,
                    "t_gates": 0,
                    "circuit": None
                }
            
            if "logical" not in results:
                results["logical"] = {
                    "depth": 0,
                    "gate_count": 0,
                    "cx_count": 0,
                    "t_gates": 0,
                    "circuit": None
                }
            
            if "optimized" not in results and "final" in results:
                results["optimized"] = results["final"]
                
            if "optimized" not in results:
                results["optimized"] = {
                    "depth": 0,
                    "gate_count": 0,
                    "cx_count": 0,
                    "t_gates": 0,
                    "circuit": None
                }
            
            if "mapped" not in results and "physical" in results:
                results["mapped"] = results["physical"]
                
            if "mapped" not in results:
                results["mapped"] = {
                    "depth": 0,
                    "gate_count": 0,
                    "cx_count": 0,
                    "t_gates": 0,
                    "circuit": None
                }
            
            return results
            
        except Exception as e:
            print(f"Error in optimize_toffoli_network adapter: {e}")
            traceback.print_exc()
            
            # Return a minimal error result
            return {
                "error": str(e),
                "logical": {"depth": 0, "circuit": None},
                "naive_physical": {"depth": 0, "circuit": None},
                "optimized": {"depth": 0, "circuit": None},
                "mapped": {"depth": 0, "circuit": None},
                "depth_reduction": 0,
                "optimization_time": 0
            }

